export async function cargarIdioma() {
  const guardado = await AsyncStorage.getItem("idioma");
  if (!guardado) return;
  const soportados = ["es", "en", "fr", "de", "it"] as const;
  const lang = (soportados as readonly string[]).includes(guardado) ? guardado : "es";
  if (lang !== guardado) {
    await AsyncStorage.setItem("idioma", lang);
  }
  await i18n.changeLanguage(lang);
}

export async function cambiarIdioma(lang: 'es' | 'en' | 'fr' | 'de' | 'it') {
  await i18n.changeLanguage(lang);
  await AsyncStorage.setItem('idioma', lang);
}

